export const productScoreMapper = {
  table: "product_scores",
  idColumn: "property_id",
  fromRow(row: Row): ProductScore & { id: string } {
    return {
      id: row.property_id,
      propertyId: row.property_id,
      weights: {
        location: row.weight_location,
        price: row.weight_price,
        legal: row.weight_legal,
        amenities: row.weight_amenities,
        livability: row.weight_livability,
        investment: row.weight_investment,
        liquidity: row.weight_liquidity,
      },
      inputs: {
        location: { value: row.score_location ?? null },
        price: { value: row.score_price ?? null },
        legal: { value: row.score_legal ?? null },
        amenities: { value: row.score_amenities ?? null },
        livability: { value: row.score_livability ?? null },
        investment: { value: row.score_investment ?? null },
        liquidity: { value: row.score_liquidity ?? null },
      },
      evaluatedAt: row.evaluated_at,
    };
  },
  toRow(item: ProductScore & { id: string }, ownerId: string): Row {
    return {
      property_id: item.propertyId,
      owner_id: ownerId,
      weight_location: item.weights.location,
      weight_price: item.weights.price,
      weight_legal: item.weights.legal,
      weight_amenities: item.weights.amenities,
      weight_livability: item.weights.livability,
      weight_investment: item.weights.investment,
      weight_liquidity: item.weights.liquidity,
      score_location: item.inputs.location.value,
      score_price: item.inputs.price.value,
      score_legal: item.inputs.legal.value,
      score_amenities: item.inputs.amenities.value,
      score_livability: item.inputs.livability.value,
      score_investment: item.inputs.investment.value,
      score_liquidity: item.inputs.liquidity.value,
      evaluated_at: item.evaluatedAt,
    };
  },
};

